/// Type-state marker of a [`GameSimFactory`] whose matching is not set yet.
///
/// It does not implement [`Matching`], so `build`, `into_builder`, and
/// `build_trial` are unavailable until [`GameSimFactory::matching`] replaces
/// it.
#[derive(Clone, Copy, Debug, Default)]
pub struct NoMatching;

/// The activation scheduler of a simulation built by a [`GameSimFactory`].
///
/// The names match the `scheduler` strings of a scenario: `"sequential"` and
/// `"random_activation"`.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[non_exhaustive]
pub enum SchedulerChoice {
    /// Activates agents in ascending id order every step
    /// ([`SequentialScheduler`]).
    #[default]
    Sequential,
    /// Shuffles the activation order every step with the engine's random
    /// stream ([`RandomActivationScheduler`]).
    RandomActivation,
}

impl SchedulerChoice {
    fn scheduler<W: WorldState>(self) -> Box<dyn Scheduler<W>> {
        match self {
            Self::Sequential => Box::new(SequentialScheduler),
            Self::RandomActivation => Box::new(RandomActivationScheduler),
        }
    }
}

/// Builds the per-step metrics mechanism for a game.
type MetricsCtor<G, X> = Arc<
    dyn Fn(&G, PayoffTiming) -> Result<Box<dyn Mechanism<GameWorld<G, X>>>, GameError>
        + Send
        + Sync
        + 'static,
>;

