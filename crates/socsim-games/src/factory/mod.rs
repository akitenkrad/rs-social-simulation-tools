//! A type-state builder for game simulations: [`GameSimFactory`].
//!
//! [`GameSimFactory`] wraps the assembly functions ([`build_world_with`] and
//! [`assemble_with`](crate::assemble_with)) with a type state and the run-time
//! checks those functions already perform. A factory holds a configuration,
//! not a simulation: [`GameSimFactory::build`],
//! [`GameSimFactory::into_builder`], and [`GameSimFactory::build_trial`] take
//! `&self` and can be called any number of times, for example once per seed
//! from several threads. The same configuration and seed always yield the same
//! world, mechanisms, and engine seed.
//!
//! All three entry points run one private procedure:
//!
//! 1. the world is built by [`build_world_with`] from the game, the
//!    registered rules, the assignment, and the initial held actions;
//! 2. the topology, if any, is attached with [`GameWorld::with_topology`];
//! 3. the selected population-dynamics type state dispatches to the matching
//!    synchronous or asynchronous assembly procedure;
//! 4. the per-step metrics, if requested, are appended as `game_metrics` with
//!    payoff descriptions matching that procedure.
//!
//! # Random streams
//!
//! A factory uses the same streams as the assembly functions, all derived
//! from the seed passed to `build`: `derive_seed(seed, &[0])` shuffles a
//! [`Assignment::Shuffled`] assignment, `derive_seed(seed, &[0, 2])` lays out
//! [`InitialActions::Shares`], `derive_seed(seed, &[2])` is the decision root,
//! `derive_seed(seed, &[3, agent, generation])` initializes rule states, and
//! the engine is seeded with `derive_seed(seed, &[1])`. A network topology is
//! generated by the caller before it is passed to
//! [`GameSimFactory::topology`]; `derive_seed(seed, &[0, 1])` is the
//! recommended stream for it.

