/// A reusable, type-checked configuration of a game simulation.
///
/// The type parameters record the parts that change the type of the
/// simulation: the game `G`, the experiment state `X`, the matching `M`, the
/// play path `P`, and the population dynamic `D`. [`GameSimFactory::new`]
/// starts with no matching ([`NoMatching`]), the pairwise play path with
/// [`NormalFormOutcome`], and no population dynamic ([`NoDynamics`]).
/// [`build`](Self::build), [`into_builder`](Self::into_builder), and
/// [`build_trial`](Self::build_trial) exist only once a matching is set, so
/// forgetting [`matching`](Self::matching) is a compile-time error. They also
/// require `G: Clone` and `X: Clone`, because every build starts from a clone
/// of the game and of the experiment state.
///
/// The play path is chosen with [`outcome`](Self::outcome) or
/// [`counting_play`](Self::counting_play) and only then wrapped with
/// [`aggregates`](Self::aggregates); the reverse order does not compile.
///
/// # Settings and defaults
///
/// | Setting | Default |
/// |---|---|
/// | [`agents`](Self::agents) | required |
/// | [`matching`](Self::matching) | required (type state) |
/// | [`history_len`](Self::history_len) | required |
/// | [`t_max`](Self::t_max) | required |
/// | [`rule`](Self::rule) | none; every rule is wrapped in an `Arc` |
/// | [`assign`](Self::assign) | every agent held with no rule, every agent on the rule with one rule, required with two or more rules |
/// | [`initial_held`](Self::initial_held) | `InitialActions::Same(0)` for games whose actions are indices (`usize`), required otherwise |
/// | [`topology`](Self::topology) | [`Topology::None`] |
/// | [`play_options`](Self::play_options) | [`PlayOptions::new`] |
/// | [`outcome`](Self::outcome) or [`counting_play`](Self::counting_play), then optionally [`aggregates`](Self::aggregates) | pairwise play with [`NormalFormOutcome`], no aggregates |
/// | [`dynamics`](Self::dynamics) or [`async_dynamics`](Self::async_dynamics) | [`NoDynamics`] |
/// | [`metrics`](Self::metrics), [`continuous_metrics`](Self::continuous_metrics) | no metrics |
/// | [`scheduler`](Self::scheduler) | [`SchedulerChoice::Sequential`] |
///
/// A missing required value is reported by `build` as [`GameError::Config`],
/// whose message starts with the name of the setting.
///
/// # Run-time checks
///
/// `build` reports every inconsistency that the assembly functions detect:
/// population dynamics with an agent on an active rule, a population dynamic
/// on a game whose roles do not share one action space, a per-step decision
/// with an agent holding several roles, a rule that does not support the game
/// (for example fictitious play on a game with more than two roles), dynamic
/// parameters that the payoff range does not allow, duplicate rule kinds, and
/// assignments to unregistered rule kinds. A built-in game checks its own
/// parameters when it is constructed; that error converts into
/// [`GameError::Catalog`].
///
/// # Recorder
///
/// A factory holds no recorder, because a recorder cannot be shared between
/// the simulations built from one factory. Attach one to the builder:
/// `factory.into_builder(seed)?.recorder(recorder).build()`.
pub struct GameSimFactory<
    G: StageGame,
    X: ExperimentState = (),
    M = NoMatching,
    P = Pairwise<NormalFormOutcome>,
    D = NoDynamics,
> {
    game: G,
    x: X,
    n_agents: Option<usize>,
    matching: M,
    rules: Vec<(String, Arc<dyn DecisionRule<G, X>>)>,
    assign: Option<Assignment>,
    initial_held: Option<InitialActions<G::Action>>,
    history_len: Option<usize>,
    t_max: Option<u64>,
    topology: Option<Topology>,
    play_options: PlayOptions<G::Action>,
    play: P,
    dynamics: D,
    metrics: Option<MetricsCtor<G, X>>,
    scheduler: SchedulerChoice,
}

impl<G, X, M, P, D> Clone for GameSimFactory<G, X, M, P, D>
where
    G: StageGame + Clone,
    X: ExperimentState + Clone,
    M: Clone,
    P: Clone,
    D: Clone,
{
    fn clone(&self) -> Self {
        Self {
            game: self.game.clone(),
            x: self.x.clone(),
            n_agents: self.n_agents,
            matching: self.matching.clone(),
            rules: self.rules.clone(),
            assign: self.assign.clone(),
            initial_held: self.initial_held.clone(),
            history_len: self.history_len,
            t_max: self.t_max,
            topology: self.topology.clone(),
            play_options: self.play_options.clone(),
            play: self.play.clone(),
            dynamics: self.dynamics.clone(),
            metrics: self.metrics.clone(),
            scheduler: self.scheduler,
        }
    }
}

impl<G: StageGame> GameSimFactory<G> {
    /// Starts a configuration for `game` without experiment state.
    pub fn new(game: G) -> Self {
        Self::with_state(game, ())
    }
}

impl<G: StageGame, X: ExperimentState> GameSimFactory<G, X> {
    /// Starts a configuration for `game` with the experiment state `x`.
    ///
    /// Every simulation built from the factory starts from a clone of `x`.
    pub fn with_state(game: G, x: X) -> Self {
        Self {
            game,
            x,
            n_agents: None,
            matching: NoMatching,
            rules: Vec::new(),
            assign: None,
            initial_held: None,
            history_len: None,
            t_max: None,
            topology: None,
            play_options: PlayOptions::new(),
            play: Pairwise::new(NormalFormOutcome),
            dynamics: NoDynamics,
            metrics: None,
            scheduler: SchedulerChoice::Sequential,
        }
    }
}

impl<G: StageGame, X: ExperimentState, M, P, D> GameSimFactory<G, X, M, P, D> {
    /// Rebuilds the factory with new type-state parts.
    fn replace<M2, P2, D2>(
        self,
        parts: impl FnOnce(M, P, D) -> (M2, P2, D2),
    ) -> GameSimFactory<G, X, M2, P2, D2> {
        let (matching, play, dynamics) = parts(self.matching, self.play, self.dynamics);
        GameSimFactory {
            game: self.game,
            x: self.x,
            n_agents: self.n_agents,
            matching,
            rules: self.rules,
            assign: self.assign,
            initial_held: self.initial_held,
            history_len: self.history_len,
            t_max: self.t_max,
            topology: self.topology,
            play_options: self.play_options,
            play,
            dynamics,
            metrics: self.metrics,
            scheduler: self.scheduler,
        }
    }

    /// Sets the number of agents (required).
    pub fn agents(mut self, n_agents: usize) -> Self {
        self.n_agents = Some(n_agents);
        self
    }

    /// Sets the matching (required); this changes the type state.
    pub fn matching<M2>(self, matching: M2) -> GameSimFactory<G, X, M2, P, D>
    where
        M2: Matching<G, X> + Clone + 'static,
    {
        self.replace(|_, play, dynamics| (matching, play, dynamics))
    }

    /// Registers `rule` under the kind name `name`.
    ///
    /// The rule is wrapped in an `Arc` and shared by every simulation built
    /// from the factory; rule state lives in the world. Registering the same
    /// name twice makes `build` fail with
    /// [`RuleError::DuplicateKind`](crate::RuleError::DuplicateKind).
    pub fn rule<R>(mut self, name: impl Into<String>, rule: R) -> Self
    where
        R: DecisionRule<G, X> + 'static,
    {
        self.rules.push((name.into(), Arc::new(rule)));
        self
    }

    /// Sets how rule kinds are assigned to agents.
    ///
    /// Without an assignment, every agent is held when no rule is registered
    /// and every agent follows the rule when exactly one is registered; with
    /// two or more rules an assignment is required.
    pub fn assign(mut self, assign: Assignment) -> Self {
        self.assign = Some(assign);
        self
    }

    /// Sets the initial held actions.
    ///
    /// The default is decided by the action type alone: when `G::Action` is
    /// `usize` (which includes every [`FiniteGame`]), the default is
    /// `InitialActions::Same(0)`; for any other action type, such as the
    /// vectors of a [`ContinuousGame`], the initial actions are required.
    pub fn initial_held(mut self, initial: InitialActions<G::Action>) -> Self {
        self.initial_held = Some(initial);
        self
    }

    /// Sets the number of past steps kept for decisions (required, positive).
    pub fn history_len(mut self, history_len: usize) -> Self {
        self.history_len = Some(history_len);
        self
    }

    /// Sets the number of steps of the simulation clock (required).
    pub fn t_max(mut self, t_max: u64) -> Self {
        self.t_max = Some(t_max);
        self
    }

    /// Attaches a topology to the world; agent `i` is node or cell `i`.
    pub fn topology(mut self, topology: Topology) -> Self {
        self.topology = Some(topology);
        self
    }

    /// Sets the play options (payoff aggregation, decision scope, and so on).
    pub fn play_options(mut self, options: PlayOptions<G::Action>) -> Self {
        self.play_options = options;
        self
    }

    /// Sets the population dynamic; this changes the type state.
    pub fn dynamics<D2>(self, dynamics: D2) -> GameSimFactory<G, X, M, P, D2>
    where
        D2: PopulationDynamics<G, X> + Clone,
    {
        self.replace(|matching, play, _| (matching, play, dynamics))
    }

    /// Sets an in-place asynchronous population step; this changes the type
    /// state.
    ///
    /// The asynchronous assembly path supports held populations with an
    /// implicit grid, network, or whole-population matching. Calling
    /// [`dynamics`](Self::dynamics) or `async_dynamics` again replaces the
    /// earlier setting, so the method called last selects the assembly path.
    pub fn async_dynamics<D2>(
        self,
        step: AsyncPopulationStep<D2>,
    ) -> GameSimFactory<G, X, M, P, AsyncPopulationStep<D2>> {
        self.replace(|matching, play, _| (matching, play, step))
    }

    /// Sets the per-step [`GameMetrics`] built from `options` (replaces any
    /// metrics set earlier).
    ///
    /// The metrics are constructed for the game at every build and run after
    /// `game_play`, as when they are added to the result of
    /// [`assemble_with`](crate::assemble_with). A factory holds at most one
    /// metrics mechanism; when more are needed, add them with
    /// `into_builder(seed)?.add_mechanism(..)`.
    ///
    /// The payoff timing in `options` is set by the factory: `AfterUpdate`
    /// after [`async_dynamics`](Self::async_dynamics) and `BeforeUpdate`
    /// otherwise, so the column descriptions match how the factory updates.
    pub fn metrics(mut self, options: MetricsOptions) -> Self
    where
        G: FiniteGame,
    {
        self.metrics = Some(Arc::new(move |game: &G, payoff_timing| {
            let metrics: Box<dyn Mechanism<GameWorld<G, X>>> = Box::new(GameMetrics::new(
                game,
                options.clone().payoff_timing(payoff_timing),
            )?);
            Ok(metrics)
        }));
        self
    }

    /// Sets the per-step [`ContinuousMetrics`] built from `options` (replaces
    /// any metrics set earlier).
    ///
    /// The metrics are constructed for the game at every build and run after
    /// `game_play`. A factory holds at most one metrics mechanism; when more
    /// are needed, add them with `into_builder(seed)?.add_mechanism(..)`.
    ///
    /// The payoff timing in `options` is set by the factory: `AfterUpdate`
    /// after [`async_dynamics`](Self::async_dynamics) and `BeforeUpdate`
    /// otherwise, so the column descriptions match how the factory updates.
    pub fn continuous_metrics(mut self, options: ContinuousMetricsOptions) -> Self
    where
        G: ContinuousGame,
    {
        self.metrics = Some(Arc::new(move |game: &G, payoff_timing| {
            let metrics: Box<dyn Mechanism<GameWorld<G, X>>> = Box::new(ContinuousMetrics::new(
                game,
                options.clone().payoff_timing(payoff_timing),
            )?);
            Ok(metrics)
        }));
        self
    }

    /// Sets the activation scheduler.
    pub fn scheduler(mut self, scheduler: SchedulerChoice) -> Self {
        self.scheduler = scheduler;
        self
    }

    /// Replaces the play path with `play`; this changes the type state.
    ///
    /// Crate-internal: a scenario chooses its play path at run time and passes
    /// it whole, so a scenario and the public setting methods build through
    /// the same procedure.
    #[cfg(feature = "config")]
    pub(crate) fn play_path<P2>(self, play: P2) -> GameSimFactory<G, X, M, P2, D>
    where
        P2: PlayPath<G, X> + Clone,
    {
        self.replace(|matching, _, dynamics| (matching, play, dynamics))
    }
}

/// Methods that choose the play path.
///
/// They exist only while the play path is [`Pairwise`] or [`Counting`]:
/// choose the outcome rule or the counting path first, then add aggregates.
/// Once [`aggregates`](GameSimFactory::aggregates) has wrapped the play path
/// in [`WithAggregates`], the play path can no longer be replaced, so the
/// aggregates cannot be dropped by mistake.
impl<G, X, M, D, O> GameSimFactory<G, X, M, Pairwise<O>, D>
where
    G: StageGame,
    X: ExperimentState,
{
    /// Evaluates encounters with the outcome rule `outcome`
    /// ([`Pairwise`]). Call it before
    /// [`aggregates`](GameSimFactory::aggregates).
    pub fn outcome<O2>(self, outcome: O2) -> GameSimFactory<G, X, M, Pairwise<O2>, D>
    where
        O2: OutcomeRule<G, X> + Clone + 'static,
    {
        self.replace(|matching, _, dynamics| (matching, Pairwise::new(outcome), dynamics))
    }

    /// Computes payoffs from action counts ([`Counting`]). Call it
    /// before [`aggregates`](GameSimFactory::aggregates).
    pub fn counting_play(self) -> GameSimFactory<G, X, M, Counting, D>
    where
        G: AnonymousGame,
    {
        self.replace(|matching, _, dynamics| (matching, Counting, dynamics))
    }

    /// Records the game's public aggregates, keeping
    /// `aggregate_history_len` rows for decisions (see
    /// [`assemble_with_aggregates`](crate::assemble_with_aggregates)).
    ///
    /// This wraps the current play path in [`WithAggregates`]; after
    /// it, [`outcome`](GameSimFactory::outcome) and
    /// [`counting_play`](GameSimFactory::counting_play) are no longer
    /// available.
    pub fn aggregates(
        self,
        aggregate_history_len: usize,
    ) -> GameSimFactory<G, X, M, WithAggregates<Pairwise<O>>, D>
    where
        G: AggregateGame,
    {
        self.replace(|matching, play, dynamics| {
            (
                matching,
                play.with_aggregates(aggregate_history_len),
                dynamics,
            )
        })
    }
}

