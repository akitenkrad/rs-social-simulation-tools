/// Runs normal-form game scenarios through the shared game trial factories.
#[derive(Debug, Default)]
pub struct NormalFormPack;

impl NormalFormPack {
    /// Names of the mechanisms accepted by normal-form scenarios.
    pub fn mechanism_names(&self) -> Vec<String> {
        SCENARIO_MECHANISM_NAMES
            .iter()
            .map(|name| (*name).to_owned())
            .collect()
    }

    /// Validates the complete scenario and its selected game family.
    pub fn validate(&self, scenario: &Scenario) -> Result<()> {
        match selected_family(scenario)? {
            GameFamily::Finite => finite_factory().validate(scenario),
            GameFamily::Continuous => continuous_factory().validate(scenario),
            other => unsupported_family(other),
        }
    }

    /// Runs all requested trial seeds.
    pub fn run_trials(
        &self,
        scenario: &Scenario,
        seeds: &[u64],
        parallel: bool,
    ) -> Result<Vec<RunResult>> {
        match selected_family(scenario)? {
            GameFamily::Finite => run_trials(scenario, &finite_factory(), seeds, parallel),
            GameFamily::Continuous => run_trials(scenario, &continuous_factory(), seeds, parallel),
            other => unsupported_family(other),
        }
    }

    /// Runs a checked parameter sweep for all requested trial seeds.
    pub fn run_sweep(
        &self,
        scenario: &Scenario,
        axes: &[SweepAxis],
        seeds: &[u64],
        parallel: bool,
    ) -> Result<Vec<CheckedSweepPoint>> {
        match selected_family(scenario)? {
            GameFamily::Finite => {
                run_trial_sweep(scenario, axes, &finite_factory(), seeds, parallel)
            }
            GameFamily::Continuous => {
                run_trial_sweep(scenario, axes, &continuous_factory(), seeds, parallel)
            }
            other => unsupported_family(other),
        }
    }
}

fn finite_factory() -> GameTrialFactory<FiniteSpec> {
    GameTrialFactory::new(RuleRegistry::finite_builtins())
}

fn continuous_factory() -> GameTrialFactory<ContinuousSpec> {
    GameTrialFactory::new(RuleRegistry::continuous_builtins())
}

fn selected_family(scenario: &Scenario) -> Result<GameFamily> {
    game_family(scenario).map_err(|error| match error {
        GameError::Config(message) => SocsimError::Config(message),
        other => SocsimError::Config(other.to_string()),
    })
}

fn unsupported_family<T>(family: GameFamily) -> Result<T> {
    Err(SocsimError::Config(format!(
        "world.game.kind: unsupported game family {family:?}"
    )))
}
